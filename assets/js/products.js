/* ---------- helpers ---------- */

function nvFamily(p) { return NV_FAMILIES[p.family] || { name: "", long: "", color: "#78909C" }; }

/* "C21H27N7O14P2" → C<sub>21</sub>H<sub>27</sub>… (leaves "· H2O" etc. readable) */
function nvFormula(f) {
  return String(f).replace(/([A-Za-z\)])(\d+)/g, "$1<sub>$2</sub>");
}

/* Human-readable quantity: "25MG" → "25 mg" */
function nvQty(p) { return p.mg.replace(/(\d)\s*MG$/i, "$1 mg"); }

